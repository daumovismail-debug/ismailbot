def _from_llm(data) -> list[dict] | None:
    """Достаём кадры из ответа Сценариста (формат может слегка варьироваться)."""
    if isinstance(data, dict):
        shots = data.get("shots") or data.get("кадры")
    elif isinstance(data, list):
        shots = data
    else:
        shots = None
    if not shots or len(shots) < 8:
        return None
    scenes = []
    for i, s in enumerate(shots[:14], 1):
        kz = s.get("voice_kz") or ""
        ru = s.get("voice_ru") or s.get("title") or ""
        # озвучиваем и подписываем казахский (если есть), русский — для проверки
        voice = kz or ru
        scenes.append({
            "id": i,
            "role": s.get("act") or s.get("role") or "СЦЕНА",
            "voice": voice,
            "voice_kz": kz,
            "voice_ru": ru,
            "beat": s.get("on_screen") or s.get("action") or s.get("beat") or "",
            "light": s.get("light", ""),
        })
    return scenes


def run(job, ctx: dict) -> str:
    idea = ctx["idea"]
    brief = ctx.get("brief", {})
    # бриф Режиссёра — вход Сценариста (единая истина: тон/хук/эмоция/конфликт)
    task = TASK_TPL.format(theme=idea["theme"]) + (
        "\n\nБриф Режиссёра (строго следуй ему): "
        f"тон={brief.get('tone','')}; конфликт={brief.get('core_conflict','')}; "
        f"тип хука={brief.get('hook_type','')}; "
        f"эмоция-цель={brief.get('target_emotion','')}; "
        f"визуал={brief.get('visual_mood','')}."
    )
    if brief.get("hero"):
        task += f"\nГерой: {brief['hero']}."
    # конкретика от автора из интервью продюсера — учти ОБЯЗАТЕЛЬНО
    if isinstance(brief.get("details"), str) and brief["details"].strip():
        task += f"\n\nПожелания и детали от автора (обязательно учти): {brief['details'].strip()}"
    # арка сезона: серия 2+ — продолжение от клиффхэнгера прошлой
    cliff = ctx.get("prev_cliffhanger")
    if job.episode > 1 and cliff:
        task += (
            f"\n\nЭто СЕРИЯ {job.episode} сезона. Прошлая серия закончилась на: "
            f"«{cliff}». Продолжи историю с этого момента — новый виток и поворот, "
            "те же герои, снова заверши резким клиффхэнгером."
        )
    data = agent_runner.run_json("scenarist", task, session_key=f"svet-{job.id}")
    scenes = _from_llm(data)
    if scenes:
        source = "Сценарист (LLM)"
    else:
        scenes = [
            {"id": i + 1, "role": r, "voice": kz, "voice_kz": kz, "voice_ru": ru,
             "beat": b, "light": lt}
            for i, (r, kz, ru, b, lt) in enumerate(_DEMO)
        ]
        source = "демо-сериал"

    ctx["scenes"] = scenes
    return f"Сценарий готов ({source}): {len(scenes)} кадров, cold open → клиффхэнгер"
